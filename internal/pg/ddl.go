package pg

import (
	"fmt"
	"strings"

	"github.com/ryangerardwilson/nebula/internal/orm"
)

type column struct {
	Name    string
	Type    string
	NotNull bool
	PK      bool
	Default string
}

func CreateSQL(model orm.Model) string {
	body := tableSQL(model.Name, columnsFrom(model))
	var b strings.Builder
	b.WriteString(body)
	for _, column := range model.Columns {
		if column.PrimaryKey && column.NotNull {
			fmt.Fprintf(&b, ";\nCOMMENT ON COLUMN %s.%s IS 'sqlx_notnull'", orm.QuoteIdent(model.Name), orm.QuoteIdent(column.Name))
		}
	}
	return b.String()
}

func AddColumnSQL(table string, column orm.Column) string {
	return "ALTER TABLE " + orm.QuoteIdent(table) + " ADD COLUMN " + columnSQL(fromORM(column))
}

func columnsFrom(model orm.Model) []column {
	out := make([]column, len(model.Columns))
	for i, column := range model.Columns {
		out[i] = fromORM(column)
	}
	return out
}

func fromORM(src orm.Column) column {
	return column{
		Name:    src.Name,
		Type:    src.Type,
		NotNull: src.NotNull,
		PK:      src.PrimaryKey,
		Default: src.Default,
	}
}

func tableSQL(name string, columns []column) string {
	var b strings.Builder
	fmt.Fprintf(&b, "CREATE TABLE %s (\n", orm.QuoteIdent(name))
	for i, column := range columns {
		b.WriteString("  " + columnSQL(column))
		if i+1 < len(columns) {
			b.WriteByte(',')
		}
		b.WriteByte('\n')
	}
	b.WriteByte(')')
	return b.String()
}

func columnSQL(column column) string {
	if column.PK && strings.EqualFold(column.Type, "integer") {
		return orm.QuoteIdent(column.Name) + " bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	}
	line := orm.QuoteIdent(column.Name) + " " + pgType(column.Type)
	if column.PK {
		line += " PRIMARY KEY"
	} else if column.NotNull {
		line += " NOT NULL"
	}
	if column.Default != "" {
		line += " DEFAULT " + column.Default
	}
	return line
}

func pgType(kind string) string {
	switch strings.ToLower(kind) {
	case "integer":
		return "bigint"
	case "real":
		return "double precision"
	case "blob":
		return "bytea"
	default:
		return "text"
	}
}
